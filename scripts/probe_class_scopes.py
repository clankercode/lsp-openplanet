#!/usr/bin/env python3
"""B067/B148: is a CLASS name usable as a SCOPE in type position?

Regenerates `docs/probes/b067-class-position-scopes.tsv`, which shipped as one
of the two ORPHAN corpora — engine gold with its method written out in a
preamble and no script anywhere in the repo, so nobody could re-derive it
(B148).

# The instrument

Two fixture shapes, each its own plugin (B068: one construct per compilation
unit — a batched run reports every name after a parse error as ACCEPTED):

    QUALIFIED   <Name>::ZZZNoSuchName v;
    BARE        <Name> v;

`ZZZNoSuchName` never exists, so the QUALIFIED shape ALWAYS fails to compile.
The datum is not whether it failed but WHICH failure the engine chose, and the
two spellings answer opposite questions:

    "Namespace 'X' doesn't exist."                          -> X is NOT a scope
    "Identifier 'ZZZNoSuchName' is not a data type in
     namespace 'X' or parent"                               -> X IS a scope

# THE DISCRIMINATOR IS TWO MESSAGE SPELLINGS, WHICH IS THE HAZARD

This corpus derives its verdict by MATCHING ENGINE PROSE. An engine upgrade can
reword either message with no change in behaviour whatsoever, and a matcher
that assumed a side would then report all 63 rows as flipped — a spectacular
false finding produced by a cosmetic change.

So `classify_message` has an explicit UNRECOGNISED outcome and NEVER defaults
to a side. If the engine rewords, every row reports UNRECOGNISED with the text
it could not parse, which reads as "the instrument no longer fits" rather than
"the language changed". That distinction is the whole reason this probe records
the raw message alongside the verdict instead of only the verdict.

# Controls, both polarities (B086)

B086's defect was a probe whose two variants failed identically: it measured
nothing while looking like it had. Here the controls must disagree with each
other or the run is void —

    SCOPE       Audio, GameData, Net, Meta, string, CMwNod, ...
    NOT_SCOPE   ZZZNoSuchClass, MwFoundations, Game, ShootMania
    PARSE_ERROR int::ZZZNoSuchName        (a primitive is not a scope at all)
    NOT_A_TYPE  bare Audio, Net, Meta ... (a namespace is not a type)
    IS_A_TYPE   bare CMwNod, string       (a class IS a type)

`CMwNod`, `CGameAction` and `CAudioListener` appear as BOTH a sample and a
control: the committed corpus measured its samples in one 41-name batch and
re-verified exactly those three in isolation. This generator runs everything in
isolation, so those three are now the like-for-like check on the old batch.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import fleet_dogfood as fleet  # noqa: E402
import issue_repro_game as repro  # noqa: E402

TOKEN = "B067CS"
MISSING = "ZZZNoSuchName"

# Verdict spellings, unchanged from the committed corpus so a regeneration is
# directly diffable against it.
SCOPE, NOT_SCOPE = "SCOPE", "NOT_SCOPE"
PARSE_ERROR, NOT_A_TYPE, IS_A_TYPE = "PARSE_ERROR", "NOT_A_TYPE", "IS_A_TYPE"
UNRECOGNISED, AMBIGUOUS = "UNRECOGNISED", "AMBIGUOUS"

CORPUS = HERE.parent / "docs/probes/b067-class-position-scopes.tsv"
SENTINEL = "# --- HAND-WRITTEN NOTES BELOW ARE PRESERVED ACROSS REGENERATIONS (B148) ---"

# Preamble lines the MACHINE owns. Everything else a human added is carried
# forward: this generator's first version replaced b071's 80-line hand-written
# preamble with an 18-line machine header, destroying methodology no game can
# be asked to reproduce. The stamp is the machine's; the prose is not.
MACHINE_LINES = (
    "# B067 probe corpus", "# Trackmania + Openplanet", "# Generated by",
    "# Openplanet.log", "# Probe: ", "#   \"", "# EVERY row was measured",
    "# corpus measured its 41", "# report every name", "# A verdict of UNRECOGNISED",
    "# the discriminator: an instrument failure",
)


def preserved_notes(path: Path) -> list[str]:
    """Hand-written preamble lines, carried forward verbatim across a regen."""
    if not path.exists():
        return []
    lines = [l for l in path.read_text(encoding="utf8").splitlines() if l.startswith("#")]
    if SENTINEL in lines:
        return lines[lines.index(SENTINEL) + 1:]
    return [l for l in lines if not any(l.startswith(m) for m in MACHINE_LINES)]

# The engine spellings this corpus discriminates on. Written as patterns rather
# than substrings so a NEAR miss (same shape, different wording) fails to match
# and is reported, instead of matching loosely and hiding the change.
RX_NOT_SCOPE = re.compile(r"Namespace '([^']+)' doesn't exist\.")
RX_SCOPE = re.compile(
    r"Identifier '" + MISSING + r"' is not a data type in namespace '([^']+)' or parent"
)
RX_NOT_A_TYPE = re.compile(r"Identifier '([^']+)' is not a data type in global namespace")
RX_PARSE = re.compile(r"Expected identifier")

SAMPLE_NAMES = [
    "CAudioScriptManager", "CAudioScriptMusic", "CGameClientTrackingScript",
    "CGameCtnAnchoredObject", "CGameActionModel", "CGameCommonItemEntityModelEdition",
    "CGxLightBall", "CHmsViewport", "CInputScriptEvent", "CInputScriptManager",
    "CAdvertisingManager", "CGameCtnMediaBlockGhostTM_SuperSKeyVal",
    "CNetMasterServerUserInfo", "CNetScriptHttpEvent", "CPlugBitmap",
    "CPlugMaterialUserInst", "CSmActionInstanceEvent", "CSmArenaRules",
    "CSystemPlatformScript", "CTrackManiaNetworkServerInfo", "CMwNod",
    "CAudioBufferKeeper", "CAudioListener", "CControlBase", "CControlButton",
    "CFunc", "CFuncColorGradient", "CGameAction", "CGameActionFxPhy",
    "CGameActionFxResources", "CGameArmorModel", "CGxFog", "CGxLightFrustum",
    "CHmsAmbientOcc", "CHmsCamera", "CInputBindingsConfig", "CInputDevice",
    "CEventMenuNavigation", "CEventMenuNavigationOnAction", "CAccountTrophyGain",
    "CAccountTrophyGainForHistory",
]

QUALIFIED_CONTROLS = [
    ("ZZZNoSuchClass", NOT_SCOPE), ("MwFoundations", NOT_SCOPE),
    ("Game", NOT_SCOPE), ("ShootMania", NOT_SCOPE),
    ("Audio", SCOPE), ("GameData", SCOPE), ("Net", SCOPE), ("Meta", SCOPE),
    ("int", PARSE_ERROR), ("string", SCOPE),
    ("CMwNod", SCOPE), ("CGameAction", SCOPE), ("CAudioListener", SCOPE),
]

BARE_CONTROLS = [
    ("GameData", NOT_A_TYPE), ("Audio", NOT_A_TYPE), ("Net", NOT_A_TYPE),
    ("Meta", NOT_A_TYPE), ("Game", NOT_A_TYPE), ("MwFoundations", NOT_A_TYPE),
    ("ShootMania", NOT_A_TYPE), ("CMwNod", IS_A_TYPE), ("string", IS_A_TYPE),
]


@dataclass
class V:
    id: str
    name: str          # the name under test, as it appears in the corpus
    shape: str         # "qualified" | "bare"
    set: str           # "SAMPLE" | "CONTROL"
    expect: str = "UNKNOWN"
    stands_for: str = ""
    fid: str = ""


def variants() -> list[V]:
    v: list[V] = []
    for n in SAMPLE_NAMES:
        v.append(V(
            id=f"q-sample-{n}", name=f"{n}::{MISSING}", shape="qualified", set="SAMPLE",
            stands_for=(
                f"a workspace writing `{n}::Something`; the resolver must know whether "
                f"an engine CLASS opens a scope in type position"
            ),
        ))
    for n, exp in QUALIFIED_CONTROLS:
        v.append(V(
            id=f"q-ctl-{n}", name=f"{n}::{MISSING}", shape="qualified", set="CONTROL",
            expect=exp,
            stands_for=(
                f"the {exp} pole of the discriminator: `{n}` is a known "
                f"{'scope' if exp == SCOPE else 'non-scope' if exp == NOT_SCOPE else 'primitive'}"
            ),
        ))
    for n, exp in BARE_CONTROLS:
        v.append(V(
            id=f"bare-ctl-{n}", name=n, shape="bare", set="CONTROL", expect=exp,
            stands_for=(
                f"`{n}` used as a TYPE with no qualification; separates "
                f"'is a namespace' from 'is a type'"
            ),
        ))
    return v


def fixture_source(v: V, suffix: str) -> str:
    """The one declaration under test. Nothing else compiles in this unit."""
    return f"{v.name} v{suffix};\n"


def classify_message(msg: str, shape: str, build_status: str, contended: bool) -> tuple[str, str]:
    """Derive the corpus verdict from ONE attributed engine message.

    Returns `(verdict, reason)`. NEVER defaults to a side: an error this
    function cannot parse is UNRECOGNISED, carrying the text, because the two
    spellings it matches on are ENGINE PROSE and an upgrade may reword them
    with no behavioural change at all. Silently treating an unmatched message
    as "not a scope" would turn a cosmetic rewording into 63 flipped rows.
    """
    if build_status == "NOT-RUN":
        return AMBIGUOUS, "the build never started; nothing was measured"
    if contended:
        return AMBIGUOUS, "another session's errors shared the log window"

    if not msg:
        if build_status == "CLEAN":
            if shape == "bare":
                return IS_A_TYPE, "compiled clean, so the bare name IS a type"
            return AMBIGUOUS, (
                "a qualified probe compiled CLEAN, which cannot happen while "
                f"'{MISSING}' does not exist — the fixture did not reach the compiler"
            )
        return AMBIGUOUS, f"no attributed error and build_status={build_status}"

    if RX_NOT_SCOPE.search(msg):
        return NOT_SCOPE, msg
    if RX_SCOPE.search(msg):
        return SCOPE, msg
    if RX_NOT_A_TYPE.search(msg):
        return NOT_A_TYPE, msg
    if RX_PARSE.search(msg):
        return PARSE_ERROR, msg
    return UNRECOGNISED, msg


def first_message(rec: dict) -> str:
    """The first error ATTRIBUTED to this fixture.

    `game_errors` only, never `foreign_errors`: Openplanet.log is shared, and
    another session's error in the same window would otherwise be read as this
    probe's answer.
    """
    for d in rec.get("game_errors", []) or []:
        m = (d.get("msg") or "").strip()
        if m:
            return m
    return ""


def write_fixture(root: Path, v: V) -> Path:
    suffix = TOKEN + re.sub(r"[^A-Za-z0-9]", "", v.id)
    pretty = f"B067cs {v.id}"
    v.fid = repro.PROBE_PREFIX + fleet.folder_id(pretty)
    plugin = root / re.sub(r"[^A-Za-z0-9-]", "_", v.id)
    plugin.mkdir(parents=True)
    plugin.joinpath("info.toml").write_text(
        "[meta]\n"
        f'name     = "{pretty}"\n'
        'author   = "clankercode"\n'
        'category = "Tests"\n'
        'version  = "0.1.0"\n'
        "\n[script]\n"
    )
    plugin.joinpath("Main.as").write_text(
        f"// B067 class-position scope probe :: {v.id}\n"
        f"// shape: {v.shape}   set: {v.set}\n"
        f"// stands in for: {v.stands_for}\n"
        + fixture_source(v, suffix)
        + "\nvoid Main() {\n"
        f'    print("{TOKEN} {v.id} ready");\n'
        "}\n"
    )
    return plugin


def run_selftest() -> int:
    """Offline checks on the variant table and the discriminator. No game."""
    failures: list[str] = []

    def check(name: str, cond: bool, why: str = "") -> None:
        if not cond:
            failures.append(f"{name}: {why}")

    vs = variants()
    for p in fleet.probe_variant_problems(vs):
        failures.append(f"variant table: {p}")

    check("row count matches the committed corpus", len(vs) == 63, f"got {len(vs)}")
    ids = [v.id for v in vs]
    check("ids unique", len(ids) == len(set(ids)), "duplicate id")
    for v in vs:
        check(f"stands_for {v.id}", bool(v.stands_for), "empty")
        check(f"probe id valid {v.id}", repro._valid_probe_id(
            repro.PROBE_PREFIX + fleet.folder_id(f"B067cs {v.id}")), "invalid fid")

    # THE DISCRIMINATOR. Each spelling must map to its own verdict, and an
    # unknown spelling must map to neither pole.
    check("not-scope spelling", classify_message(
        "Namespace 'Game' doesn't exist.", "qualified", "REJECTED", False)[0] == NOT_SCOPE)
    check("scope spelling", classify_message(
        f"Identifier '{MISSING}' is not a data type in namespace 'Audio' or parent",
        "qualified", "REJECTED", False)[0] == SCOPE)
    check("global-namespace spelling", classify_message(
        "Identifier 'Audio' is not a data type in global namespace",
        "bare", "REJECTED", False)[0] == NOT_A_TYPE)
    check("parse spelling", classify_message(
        "Expected identifier", "qualified", "REJECTED", False)[0] == PARSE_ERROR)

    # THE CENTRAL GUARD: a reworded message is UNRECOGNISED, not a side.
    for reworded in [
        "Namespace 'Game' does not exist.",          # `doesn't` -> `does not`
        "Namespace 'Game' was not found.",
        f"Identifier '{MISSING}' is not a type in namespace 'Audio'",
        "some entirely new engine wording",
    ]:
        verdict, _ = classify_message(reworded, "qualified", "REJECTED", False)
        check(f"reworded is UNRECOGNISED: {reworded[:40]}", verdict == UNRECOGNISED,
              f"a reworded message was classified {verdict}, which would read as a "
              f"behaviour change caused by an engine rewording")

    # A clean build means IS_A_TYPE only for the BARE shape. A qualified probe
    # cannot compile while the missing name is missing, so a CLEAN there means
    # the fixture never reached the compiler.
    check("bare clean is IS_A_TYPE", classify_message(
        "", "bare", "CLEAN", False)[0] == IS_A_TYPE)
    check("qualified clean is AMBIGUOUS", classify_message(
        "", "qualified", "CLEAN", False)[0] == AMBIGUOUS,
        "a qualified probe reporting CLEAN measured nothing and must not be a verdict")

    # Failure to measure is never a verdict (B118).
    check("NOT-RUN is AMBIGUOUS", classify_message(
        "Namespace 'Game' doesn't exist.", "qualified", "NOT-RUN", False)[0] == AMBIGUOUS,
        "a build that never ran produced a verdict")
    check("contended is AMBIGUOUS", classify_message(
        "Namespace 'Game' doesn't exist.", "qualified", "REJECTED", True)[0] == AMBIGUOUS,
        "a contended window produced a verdict")

    # Attribution: foreign errors must never be read as ours.
    check("foreign errors ignored", first_message(
        {"game_errors": [], "foreign_errors": [{"msg": "someone else's error"}]}) == "",
        "a foreign error was read as this probe's answer")
    check("attributed error used", first_message(
        {"game_errors": [{"msg": "mine"}]}) == "mine")

    # Regenerating must not eat hand-written prose (the b071 lesson).
    check("preserved_notes finds the sentinel",
          preserved_notes(CORPUS) == [] or isinstance(preserved_notes(CORPUS), list))
    if CORPUS.exists():
        body = "\n".join(preserved_notes(CORPUS))
        check("machine stamp is not carried forward as prose",
              "Trackmania + Openplanet" not in body,
              "the stamp line would be duplicated on every regeneration")

    print(f"b067 probe selftest: {len(vs)} variants, {len(failures)} failure(s)")
    for f in failures:
        print(f"  FAIL {f}")
    return 1 if failures else 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv")
    ap.add_argument("--only")
    ap.add_argument("--selftest", action="store_true",
                    help="offline checks on the variant table and discriminator")
    args = ap.parse_args()
    if args.selftest:
        return run_selftest()

    vs = variants()
    if args.only:
        vs = [v for v in vs if v.id.startswith(args.only)]
        if not vs:
            print(f"no variant matches {args.only!r}", file=sys.stderr)
            return 2

    problems = fleet.probe_variant_problems(vs)
    if problems:
        print("THE VARIANT TABLE CANNOT MEASURE:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 5

    if not fleet.game_alive():
        print("game/RemoteBuild not reachable; refusing to report a verdict", file=sys.stderr)
        return 3
    strays = repro.probe_dirs_present(fleet.OPN_PLUGINS)
    if strays:
        print(f"stranded probe fixtures present, refusing to run (B077): {strays}",
              file=sys.stderr)
        return 4

    version = _live_version()
    tmp = Path(tempfile.mkdtemp(prefix="b067cs-"))
    rows: list[dict] = []
    try:
        for v in vs:
            rec = repro.probe(write_fixture(tmp, v))
            msg = first_message(rec)
            verdict, reason = classify_message(
                msg, v.shape, rec.get("build_status", "NOT-RUN"), bool(rec.get("contended")))
            rows.append({
                "name": v.name, "set": v.set, "verdict": verdict,
                "message": msg, "id": v.id, "expect": v.expect,
                "stands_for": v.stands_for, "reason": reason,
            })
            flag = ""
            if v.expect != "UNKNOWN":
                flag = "  <-- CONTROL OK" if verdict == v.expect else \
                       f"  <-- CONTROL FAILED (expected {v.expect})"
            print(f"{verdict:12s} {v.name:52s}{flag}", flush=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    left = repro.probe_dirs_present(fleet.OPN_PLUGINS)
    print()
    print(f"B077 sweep: {'clean' if not left else 'STRANDED: ' + repr(left)}")

    run_problems = fleet.probe_run_problems(rows)
    if run_problems:
        print("THE RUN IS NOT EVIDENCE:", file=sys.stderr)
        for pr in run_problems:
            print(f"  - {pr}", file=sys.stderr)

    unrec = [r for r in rows if r["verdict"] == UNRECOGNISED]
    if unrec:
        print()
        print(f"{len(unrec)} row(s) UNRECOGNISED — the engine's wording no longer matches")
        print("this probe's discriminator. That is an INSTRUMENT failure, not a")
        print("behaviour change; update the patterns before reading these as findings:")
        for r in unrec[:5]:
            print(f"  {r['name']}: {r['message']}")

    if args.tsv:
        _write_tsv(Path(args.tsv), rows, version)
        print(f"\nwrote {len(rows)} rows to {args.tsv}")

    if run_problems or left:
        return 1
    bad = [r for r in rows if r["expect"] != "UNKNOWN" and r["verdict"] != r["expect"]]
    return 1 if bad else 0


def _live_version() -> tuple[str, str]:
    try:
        import regen_golds  # noqa: PLC0415
        return (regen_golds.live_engine_version() or "UNKNOWN",
                regen_golds.live_engine_build() or "UNKNOWN")
    except Exception:
        return ("UNKNOWN", "UNKNOWN")


def _write_tsv(path: Path, rows: list[dict], version: tuple[str, str]) -> None:
    import datetime
    ver, build = version
    # Read BEFORE opening for write, or the prose is already gone.
    notes = preserved_notes(CORPUS)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as fh:
        fh.write("# B067 probe corpus - CLASS-position scope verdicts, live game.\n")
        # STAMPED BY THE MACHINE (B148). The version this corpus previously
        # carried was hand-written and did not match any logged session.
        fh.write(f"# Trackmania + Openplanet {ver} ({build}), RemoteBuild, "
                 f"{datetime.date.today().isoformat()}.\n")
        fh.write(f"# Generated by scripts/probe_class_scopes.py. Stamp read from\n"
                 f"# Openplanet.log by the runner, never typed by a human.\n")
        fh.write(f"# Probe: '<name>::{MISSING} v;' in TYPE position. Paired discriminator:\n")
        fh.write(f"#   \"Namespace 'X' doesn't exist.\"                          -> X is NOT a scope\n")
        fh.write(f"#   \"Identifier '{MISSING}' is not a data type in ...\"  -> X IS a scope\n")
        fh.write("# EVERY row was measured in its OWN compilation unit (B068). The previous\n")
        fh.write("# corpus measured its 41 SAMPLE rows in one batch, which B068 showed can\n")
        fh.write("# report every name after a parse error as ACCEPTED.\n")
        fh.write("# A verdict of UNRECOGNISED means the engine's wording no longer matches\n")
        fh.write("# the discriminator: an instrument failure, NOT a behaviour change.\n")
        fh.write("#\n")
        fh.write(SENTINEL + "\n")
        for line in notes:
            fh.write(line.rstrip() + "\n")
        fh.write("name\tset\tverdict\tmessage\n")
        for r in rows:
            fh.write(f"{r['name']}\t{r['set']}\t{r['verdict']}\t{r['message']}\n")


if __name__ == "__main__":
    sys.exit(main())
