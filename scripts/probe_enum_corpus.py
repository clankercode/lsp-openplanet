#!/usr/bin/env python3
"""
probe_enum_corpus.py — regenerate the game-verdict corpora in docs/probes/.

Submits enum spellings and bare enum-value names to the LIVE game compiler
(Openplanet RemoteBuild) and records what it says, verbatim. Produced the two
tables B056 and B057 cite as their starting corpus.

    scripts/probe_enum_corpus.py --dump-enums out.jsonl
    scripts/probe_enum_corpus.py --b052 docs/probes/b052-qualified-enum-spellings.tsv
    scripts/probe_enum_corpus.py --b053 docs/probes/b053-bare-enum-values.tsv
    echo 'UI::VirtualKey' | scripts/probe_enum_corpus.py --names - --template TYPE

Requires Trackmania + Openplanet running with RemoteBuild on 127.0.0.1:30000.
There is ONE game on ONE port and lanes share it — coordinate before running.
Never writes the fleet ledger.

READ docs/probes/README.md FIRST. In particular: a game REJECT is evidence
about the engine, a game ACCEPT on an unrecognised prefix may only be an
artefact of that machine's installed plugins.

The candidate list is built from the crate's OWN loader (`--dump-enums`, which
runs the `zz_probe_enum_dump` test), never by re-deriving key generation in
Python. Re-deriving is what produced two confidently wrong counts in this
repo's history — see B046 and B053.
"""
from __future__ import annotations

import argparse
import collections
import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent

sys.path.insert(0, str(HERE))
import fleet_dogfood as fleet  # noqa: E402

# Same landmine as issue_repro_game.py: this script must never write the
# production ledger.
fleet.save_state = lambda st: (_ for _ in ()).throw(
    RuntimeError("probe_enum_corpus must not write the fleet ledger")
)

PROBE_ID = "lsp-enum-corpus-probe"

INFO = """[meta]
name     = "LSP Enum Corpus Probe"
author   = "clankercode"
category = "Tests"
version  = "0.1.0"

[script]
"""


# ---- source list ------------------------------------------------------------
def dump_enums(dest: Path) -> list[dict]:
    """Enum keys straight from the crate's loader, via a dump test."""
    subprocess.run(
        ["cargo", "test", "-j", "2", "--test", "zz_probe_enum_dump", "--", "--ignored"],
        cwd=REPO,
        check=True,
        env={**__import__("os").environ, "PROBE_ENUM_DUMP": str(dest)},
    )
    return [json.loads(line) for line in dest.read_text().splitlines() if line.strip()]


# ---- RemoteBuild ------------------------------------------------------------
def build_source(names: list[str], template: str) -> tuple[str, int]:
    header = "// generated by scripts/probe_enum_corpus.py\n"
    if template == "VALUE":
        header += "void Probe() {\n"
    body = [
        f"{n} probe_{i};" if template == "TYPE" else f'    print("" + {n});'
        for i, n in enumerate(names)
    ]
    first_line = header.count("\n") + 1
    tail = "}\n\nvoid Main() { Probe(); }\n" if template == "VALUE" else "\nvoid Main() {}\n"
    return header + "\n".join(body) + "\n" + tail, first_line


def run_batch(names: list[str], template: str) -> dict[str, str]:
    """Submit one batch; return name -> the game's message ('' when accepted)."""
    if not fleet.rb_alive():
        raise SystemExit("RemoteBuild is not alive — is the game running?")
    dest = fleet.OPN_PLUGINS / PROBE_ID
    if dest.exists():
        shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir(parents=True, exist_ok=True)
    src, first_line = build_source(names, template)
    (dest / "info.toml").write_text(INFO)
    (dest / "Main.as").write_text(src)
    mark = fleet.log_size()
    try:
        fleet.rb_route(
            "load_plugin", {"id": PROBE_ID, "source": "user", "type": "folder"}, timeout=25
        )
        time.sleep(3.0)
        diags = fleet.parse_game_diagnostics(fleet.read_log_window(mark, PROBE_ID))
        by_line: dict[int, str] = {}
        for d in diags:
            if d["sev"] == "ERR":
                by_line.setdefault(d["line"], d["msg"])
        return {n: by_line.get(first_line + i, "") for i, n in enumerate(names)}
    finally:
        fleet.rb_route("unload_plugin", {"id": PROBE_ID}, timeout=15)
        time.sleep(0.5)
        shutil.rmtree(dest, ignore_errors=True)


def probe(names: list[str], template: str, batch: int = 200) -> dict[str, str]:
    out: dict[str, str] = {}
    for start in range(0, len(names), batch):
        chunk = names[start : start + batch]
        out.update(run_batch(chunk, template))
        print(f"  probed {start + len(chunk)}/{len(names)}", file=sys.stderr)
    return out


# ---- corpora ----------------------------------------------------------------
def spellings_for(enums: list[dict]) -> list[str]:
    """Every trailing-path spelling of every named enum key, plus the bare tail."""
    seen: dict[str, None] = {}
    for e in enums:
        if e["anonymous"]:
            continue
        segments = e["key"].split("::")
        for i in range(len(segments)):
            seen.setdefault("::".join(segments[i:]), None)
    return list(seen)


def write_b052(enums: list[dict], dest: Path) -> None:
    names = spellings_for(enums)
    print(f"B052: probing {len(names)} qualified spellings", file=sys.stderr)
    verdicts = probe(names, "TYPE")
    with dest.open("w") as f:
        f.write("# B052 probe corpus - qualified enum/type spellings, live game verdicts.\n")
        f.write(f"# {fleet.rb_route('get_status', {}).get('data', '?')}; see README.md.\n")
        f.write("# Columns: spelling <TAB> verdict <TAB> the game's verbatim message\n")
        f.write("spelling\tverdict\tgame_message\n")
        for n in sorted(verdicts):
            msg = verdicts[n]
            f.write(f"{n}\t{'REJECTED' if msg else 'ACCEPTED'}\t{msg}\n")


def write_b053(enums: list[dict], dest: Path) -> None:
    by_value: dict[str, list[str]] = collections.defaultdict(list)
    for e in enums:
        if e["anonymous"]:
            continue
        for value, _ in e["values"]:
            by_value[value].append(e["key"])
    names = sorted(by_value)
    print(f"B053: probing {len(names)} bare value names", file=sys.stderr)
    verdicts = probe(names, "VALUE")

    # Globally visible: key depth <= 1 once the synthetic module prefix is
    # dropped. Counted by NAME, because the loader keys one engine enum under
    # several modules — the dedup trap, see README.md.
    global_owners: dict[str, set[str]] = collections.defaultdict(set)
    for e in enums:
        if e["anonymous"] or e["key"].count("::") > 1:
            continue
        short = e["key"].rsplit("::", 1)[-1]
        if not verdicts_type_accepts(short):
            continue
        for value, _ in e["values"]:
            global_owners[value].add(short)

    def verdict(msg: str) -> str:
        if not msg:
            return "ACCEPTED"
        if "multiple matching enum values" in msg:
            return "AMBIGUOUS"
        if msg.startswith("No matching symbol"):
            return "NO_SYMBOL"
        return "OTHER"

    with dest.open("w") as f:
        f.write("# B053 probe corpus - every bare value name of a NAMED enum.\n")
        f.write("# global_enum_owners: distinct NAMES of globally visible enums carrying it\n")
        f.write("#   (the count that decides the verdict). all_index_keys is NOT that count.\n")
        f.write("value\tverdict\tgame_message\tglobal_enum_owners\tall_index_keys\n")
        for n in names:
            msg = verdicts[n]
            f.write(
                f"{n}\t{verdict(msg)}\t{msg}\t"
                f"{';'.join(sorted(global_owners.get(n, ())))}\t"
                f"{';'.join(sorted(by_value[n]))}\n"
            )


_TYPE_ACCEPT_CACHE: dict[str, bool] = {}


def verdicts_type_accepts(short: str) -> bool:
    """Does the game accept the bare enum NAME as a type? Cached per run."""
    if short not in _TYPE_ACCEPT_CACHE:
        _TYPE_ACCEPT_CACHE[short] = not probe([short], "TYPE")[short]
    return _TYPE_ACCEPT_CACHE[short]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dump-enums", type=Path, help="write the loader's enum keys and stop")
    ap.add_argument("--b052", type=Path, help="regenerate the qualified-spelling corpus")
    ap.add_argument("--b053", type=Path, help="regenerate the bare-value corpus")
    ap.add_argument("--names", help="probe an explicit newline-separated list ('-' for stdin)")
    ap.add_argument("--template", default="TYPE", choices=["TYPE", "VALUE"])
    a = ap.parse_args()

    if a.names:
        text = sys.stdin.read() if a.names == "-" else Path(a.names).read_text()
        names = [n for n in text.splitlines() if n.strip()]
        for n, msg in probe(names, a.template).items():
            print(f"{'REJECT' if msg else 'ACCEPT'}\t{n}\t{msg}")
        return

    scratch = Path(a.dump_enums or (REPO / "target" / "probe-enums.jsonl"))
    scratch.parent.mkdir(parents=True, exist_ok=True)
    enums = dump_enums(scratch)
    print(f"loader reported {len(enums)} enum keys", file=sys.stderr)
    if a.dump_enums:
        return
    if a.b052:
        write_b052(enums, a.b052)
    if a.b053:
        write_b053(enums, a.b053)
    if not (a.b052 or a.b053):
        ap.error("nothing to do: pass --b052, --b053, --names or --dump-enums")


if __name__ == "__main__":
    main()
