import collections
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent

sys.path.insert(0, str(HERE))
import fleet_dogfood as fleet  # noqa: E402

# Same landmine as issue_repro_game.py: this script must never write the
# production ledger.
fleet.save_state = lambda st: (_ for _ in ()).throw(
    RuntimeError("probe_enum_corpus must not write the fleet ledger")
)

PROBE_ID = "lsp-enum-corpus-probe"

# Names no game database can define, used as the positive control described in
# build_source. TYPE position needs a type name; VALUE position needs a value.
SENTINEL_TYPE = "ZZZB068SentinelNoSuchType"
SENTINEL_VALUE = "ZZZB068SentinelNoSuchValue"

# `read_log_window` keeps every line containing "ERR" or "WARN", from any
# plugin, and attribution matches on line NUMBER. Without pinning the file, an
# unrelated plugin compiling in the same window can land an error on our
# sentinel's line number and certify a unit that never ran.
PROBE_FILE = f"{PROBE_ID}/Main.as"

INFO = """[meta]
name     = "LSP Enum Corpus Probe"
author   = "clankercode"
category = "Tests"
version  = "0.1.0"

[script]
"""


# ---- source list ------------------------------------------------------------
def dump_enums(dest: Path) -> list[dict]:
    """Enum keys straight from the crate's loader, via a dump test."""
    subprocess.run(
        ["cargo", "test", "-j", "2", "--test", "zz_probe_enum_dump", "--", "--ignored"],
        cwd=REPO,
        check=True,
        env={**__import__("os").environ, "PROBE_ENUM_DUMP": str(dest)},
    )
    return [json.loads(line) for line in dest.read_text().splitlines() if line.strip()]


# ---- RemoteBuild ------------------------------------------------------------
def build_source(names: list[str], template: str) -> tuple[str, int, int]:
    """Source, the line the first name lands on, and the SENTINEL's line.

    The sentinel is a name the game is guaranteed to reject for a SEMANTIC
    reason, emitted as the last probed line. It is a positive control: if its
    diagnostic comes back, semantic analysis reached the end of the unit, and
    only then does the silence on any other line mean "accepted". See B068 --
    without it, a parse error anywhere aborts the unit and every remaining name
    is recorded ACCEPTED on the strength of a diagnostic that was never
    produced.
    """
    header = "// generated by scripts/probe_enum_corpus.py\n"
    if template == "VALUE":
        header += "void Probe() {\n"
    sentinel = SENTINEL_TYPE if template == "TYPE" else SENTINEL_VALUE
    body = [
        f"{n} probe_{i};" if template == "TYPE" else f'    print("" + {n});'
        for i, n in enumerate([*names, sentinel])
    ]
    first_line = header.count("\n") + 1
    sentinel_line = first_line + len(names)
    tail = "}\n\nvoid Main() { Probe(); }\n" if template == "VALUE" else "\nvoid Main() {}\n"
    return header + "\n".join(body) + "\n" + tail, first_line, sentinel_line


def attribute(
    names: list[str],
    first_line: int,
    diags: list[dict],
    sentinel_line: int,
    source_file: str = PROBE_FILE,
) -> dict[str, str | None]:
    """Map each name to the game's message: '' accepted, text rejected, None unknown.

    `None` is the whole point of B068. The old version returned '' for any line
    that drew no diagnostic, which conflates two very different situations:

      - the game analysed this line and had nothing to say  -> ACCEPTED
      - the game never analysed this line at all            -> nothing is known

    A parse error anywhere aborts the unit before semantic analysis, so the
    second case produced a full corpus of confident ACCEPTEDs. The sentinel
    tells them apart: it is a name the game must reject semantically, sitting
    on the last probed line, so its diagnostic coming back is proof that
    analysis ran to the end.

    Note the asymmetry -- a diagnostic ON a name's line is believed even when
    the sentinel is missing. That direction is evidence rather than silence:
    the game named that line. It is also what lets an isolated name report its
    own parse error as a REJECT, in the very run where that error is what took
    the sentinel down.
    """
    by_line: dict[int, str] = {}
    for d in diags:
        # The file check is load-bearing, not defensive tidiness: the log
        # window is shared with every other plugin the game compiles.
        if d["sev"] == "ERR" and d.get("file") == source_file:
            by_line.setdefault(d["line"], d["msg"])
    analysis_reached_the_end = sentinel_line in by_line
    out: dict[str, str | None] = {}
    for i, n in enumerate(names):
        msg = by_line.get(first_line + i)
        if msg is not None:
            out[n] = msg
        else:
            out[n] = "" if analysis_reached_the_end else None
    return out


def type_accepts(msg: str | None) -> bool | None:
    """Did the game accept this name as a type? `None` = we do not know.

    Kept separate from the caller because collapsing the unknown into `False`
    is the B068 mistake one layer up: it would silently drop an enum from the
    globally-visible set on the strength of a probe that never ran.
    """
    return None if msg is None else msg == ""


def run_batch(names: list[str], template: str) -> dict[str, str | None]:
    """Submit one batch; return name -> the game's message ('' when accepted)."""
    if not fleet.rb_alive():
        raise SystemExit("RemoteBuild is not alive — is the game running?")
    dest = fleet.OPN_PLUGINS / PROBE_ID
    if dest.exists():
        shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir(parents=True, exist_ok=True)
    src, first_line, sentinel_line = build_source(names, template)
    (dest / "info.toml").write_text(INFO)
    (dest / "Main.as").write_text(src)
    mark = fleet.log_size()
    try:
        fleet.rb_route(
            "load_plugin", {"id": PROBE_ID, "source": "user", "type": "folder"}, timeout=25
        )
        time.sleep(3.0)
        diags = fleet.parse_game_diagnostics(fleet.read_log_window(mark, PROBE_ID))
        return attribute(names, first_line, diags, sentinel_line)
    finally:
        fleet.rb_route("unload_plugin", {"id": PROBE_ID}, timeout=15)
        time.sleep(0.5)
        shutil.rmtree(dest, ignore_errors=True)


def probe(
    names: list[str],
    template: str,
    batch: int = 200,
    runner=None,
) -> dict[str, str | None]:
    """Probe every name, re-running in isolation anything a batch left unknown.

    `runner` exists so the retry policy can be tested without a game; it
    defaults to the real one.

    A batch that hit a parse abort yields `None` for its survivors, and those
    get one round trip each. That is slow exactly when it has to be — a batch
    of 200 with one unparseable name costs 200 extra probes — and it only
    happens on a batch the old code would have silently reported as ACCEPTED.
    """
    if batch < 1:
        # `range(0, n, -1)` is empty, so a negative batch silently probed
        # NOTHING and the writers then emitted a header-only corpus with exit
        # 0 -- a complete-looking file containing no data at all.
        raise ValueError(f"batch must be >= 1, got {batch}")
    send = runner or run_batch
    out: dict[str, str | None] = {}
    for start in range(0, len(names), batch):
        chunk = names[start : start + batch]
        got = send(chunk, template)
        unknown = [n for n in chunk if got[n] is None]
        out.update({n: v for n, v in got.items() if v is not None})
        if unknown:
            print(
                f"  batch at {start}: analysis did not reach the end "
                f"({len(unknown)}/{len(chunk)} unproven) — re-probing in isolation",
                file=sys.stderr,
            )
            for n in unknown:
                out[n] = send([n], template)[n]
        print(f"  probed {start + len(chunk)}/{len(names)}", file=sys.stderr)
    still_unknown = sorted(n for n, v in out.items() if v is None)
    if still_unknown:
        print(
            f"  WARNING: {len(still_unknown)} name(s) undetermined even in isolation; "
            "recorded as UNDETERMINED, not ACCEPTED",
            file=sys.stderr,
        )
    return out


# ---- corpora ----------------------------------------------------------------
def spellings_for(enums: list[dict]) -> list[str]:
    """Every trailing-path spelling of every named enum key, plus the bare tail."""
    seen: dict[str, None] = {}
    for e in enums:
        if e["anonymous"]:
            continue
        segments = e["key"].split("::")
        for i in range(len(segments)):
            seen.setdefault("::".join(segments[i:]), None)
    return list(seen)


def publish(dest: Path, text: str, undetermined: int, what: str) -> None:
    """Write `text` to `dest` only if it is fit to be consumed.

    The first version wrote the corpus, then exited non-zero. That leaves a
    complete-looking TSV on disk that `resolver.rs` will happily read, and it
    maps an unrecognised verdict to "the LSP must REJECT this" without
    complaining -- so an ignored exit code turns unknowns into asserted facts.
    An unusable corpus is parked beside the target instead, never on it.
    """
    partial = dest.with_name(dest.name + ".partial")
    if undetermined:
        _atomic_write(partial, text)
        print(
            f"  {what}: {undetermined} name(s) undetermined; wrote {partial.name} "
            f"and left {dest.name} untouched",
            file=sys.stderr,
        )
        return
    _atomic_write(dest, text)
    # A leftover .partial from an earlier bad run would otherwise sit next to a
    # now-good corpus and read as if this run had failed.
    partial.unlink(missing_ok=True)


def _atomic_write(dest: Path, text: str) -> None:
    """Write via a same-directory temp file and rename.

    `write_text` truncates first, so a crash or a concurrent reader can see a
    half-written corpus. `os.replace` is atomic within a filesystem, so a
    reader sees either the old file or the complete new one.
    """
    tmp = dest.with_name(dest.name + ".tmp")
    with tmp.open("w") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, dest)


def type_verdict(msg: str | None) -> str:
    """Three states, not two. `None` is "the game never analysed this name",
    which must never collapse into ACCEPTED -- that collapse IS B068."""
    if msg is None:
        return "UNDETERMINED"
    return "REJECTED" if msg else "ACCEPTED"


def write_b052(enums: list[dict], dest: Path, batch: int = 200) -> int:
    names = spellings_for(enums)
    print(f"B052: probing {len(names)} qualified spellings", file=sys.stderr)
    verdicts = probe(names, "TYPE", batch=batch)
    rows = [
        "# B052 probe corpus - qualified enum/type spellings, live game verdicts.\n",
        f"# {fleet.rb_route('get_status', {}).get('data', '?')}; see README.md.\n",
        "# Columns: spelling <TAB> verdict <TAB> the game's verbatim message\n",
        "spelling\tverdict\tgame_message\n",
    ]
    for n in sorted(verdicts):
        msg = verdicts[n]
        rows.append(f"{n}\t{type_verdict(msg)}\t{msg or ''}\n")
    undetermined = sum(1 for m in verdicts.values() if m is None)
    publish(dest, "".join(rows), undetermined, "B052")
    return undetermined


def value_verdict(msg: str | None) -> str:
    """B053's vocabulary. Module level so a re-probe scores rows the SAME way
    the corpus was written; a private copy in a checker is how two readings of
    one file quietly diverge."""
    if msg is None:
        return "UNDETERMINED"  # analysis never ran for this name (B068)
    if not msg:
        return "ACCEPTED"
    if "multiple matching enum values" in msg:
        return "AMBIGUOUS"
    if msg.startswith("No matching symbol"):
        return "NO_SYMBOL"
    return "OTHER"


def write_b053(enums: list[dict], dest: Path, batch: int = 200) -> int:
    by_value: dict[str, list[str]] = collections.defaultdict(list)
    for e in enums:
        if e["anonymous"]:
            continue
        for value, _ in e["values"]:
            by_value[value].append(e["key"])
    names = sorted(by_value)
    print(f"B053: probing {len(names)} bare value names", file=sys.stderr)
    verdicts = probe(names, "VALUE", batch=batch)

    # Globally visible: key depth <= 1 once the synthetic module prefix is
    # dropped. Counted by NAME, because the loader keys one engine enum under
    # several modules — the dedup trap, see README.md.
    global_owners: dict[str, set[str]] = collections.defaultdict(set)
    undetermined_owners: set[str] = set()
    for e in enums:
        if e["anonymous"] or e["key"].count("::") > 1:
            continue
        short = e["key"].rsplit("::", 1)[-1]
        accepts = verdicts_type_accepts(short)
        if accepts is None:
            # We do not know whether this enum is globally visible, so we
            # cannot say whether it owns these values. Silently skipping it
            # would quietly shrink global_enum_owners -- the column that
            # DECIDES the verdict -- on the strength of a probe that never
            # ran. Count it so the corpus is not published.
            undetermined_owners.add(short)
            continue
        if not accepts:
            continue
        for value, _ in e["values"]:
            global_owners[value].add(short)

    verdict = value_verdict
    rows = [
        "# B053 probe corpus - every bare value name of a NAMED enum.\n",
        "# global_enum_owners: distinct NAMES of globally visible enums carrying it\n",
        "#   (the count that decides the verdict). all_index_keys is NOT that count.\n",
        "value\tverdict\tgame_message\tglobal_enum_owners\tall_index_keys\n",
    ]
    for n in names:
        msg = verdicts[n]
        rows.append(
            f"{n}\t{verdict(msg)}\t{msg or ''}\t"
            f"{';'.join(sorted(global_owners.get(n, ())))}\t"
            f"{';'.join(sorted(by_value[n]))}\n"
        )
    # Two independent ways this corpus can be incomplete: a value we could not
    # probe, and an OWNER we could not probe. The second does not show up in
    # any row's verdict, which is exactly why it needs counting here.
    unknown_values = sum(1 for m in verdicts.values() if m is None)
    # Summed only as a PUBLICATION GATE -- either kind makes the corpus
    # unusable. They are different populations and the total is not a count of
    # undetermined rows, so both are reported.
    undetermined = unknown_values + len(undetermined_owners)
    if undetermined:
        print(
            f"  B053: {unknown_values} value(s) and {len(undetermined_owners)} "
            "owner enum(s) undetermined; owners missing from global_enum_owners "
            "would silently change the verdict column",
            file=sys.stderr,
        )
    publish(dest, "".join(rows), undetermined, "B053")
    return undetermined


_TYPE_ACCEPT_CACHE: dict[str, bool | None] = {}


def verdicts_type_accepts(short: str) -> bool | None:
    """Does the game accept the bare enum NAME as a type? `None` = unknown."""
    if short not in _TYPE_ACCEPT_CACHE:
        _TYPE_ACCEPT_CACHE[short] = type_accepts(probe([short], "TYPE")[short])
    return _TYPE_ACCEPT_CACHE[short]


# ---- selftest ---------------------------------------------------------------
# Offline. Drives the attribution logic with SYNTHETIC diagnostics, so the part
# of B068 that invents a false ACCEPTED is testable with no game running. What
# still needs the game is re-probing the shipped corpora (B068 work item 2).


def _err(line: int, msg: str) -> dict:
    """One ERR diagnostic in the shape fleet.parse_game_diagnostics returns."""
    return {"file": PROBE_FILE, "line": line, "col": 1, "sev": "ERR", "msg": msg}


class _FakeGame:
    """A stand-in compiler with the one behaviour B068 turns on.

    A parse error aborts the whole unit before semantic analysis, so the game
    reports that one diagnostic and nothing else -- including nothing for the
    sentinel. Anything else gets ordinary per-line semantic diagnostics. The
    sentinel is always rejected, which is the property the real probe relies on.
    """

    def __init__(self, parse_errors: set[str], semantic_rejects: set[str]) -> None:
        self.parse_errors = parse_errors
        self.semantic_rejects = semantic_rejects
        self.calls: list[list[str]] = []

    def __call__(self, names: list[str], template: str) -> dict[str, str | None]:
        self.calls.append(list(names))
        src, first_line, sentinel_line = build_source(names, template)

        # Read the names back OUT of the generated source rather than assuming
        # what build_source emitted. A fake that recreates the layout from its
        # own knowledge would keep "seeing" a sentinel that build_source had
        # stopped writing, and would pass a mutation that deleted it.
        probed: dict[int, str] = {}
        for offset, line in enumerate(src.split("\n"), start=1):
            text = line.strip()
            if template == "TYPE" and text.endswith(";") and " probe_" in text:
                probed[offset] = text.split(" probe_", 1)[0]
            elif template == "VALUE" and text.startswith('print("" + '):
                probed[offset] = text[len('print("" + ') : -len(");")]

        aborted = sorted(ln for ln, n in probed.items() if n in self.parse_errors)
        if aborted:
            diags = [_err(aborted[0], "Expected identifier")]
        else:
            diags = [
                _err(ln, f"Identifier '{n}' is not a data type")
                for ln, n in sorted(probed.items())
                if n in self.semantic_rejects or n in (SENTINEL_TYPE, SENTINEL_VALUE)
            ]
        return attribute(names, first_line, diags, sentinel_line)


def run_selftest() -> int:
    failures: list[str] = []

    def check(what: str, got, want) -> None:
        if got != want:
            failures.append(f"{what}\n    got  {got!r}\n    want {want!r}")

    # The B068 red demonstration, verbatim from the ticket. `int::` is a parse
    # error because `int` is a keyword; a parse abort kills the whole unit
    # before semantic analysis, so CMwNod::ZZZNoSuchName draws no diagnostic of
    # its own -- and must NOT be reported as accepted on that silence.
    names = ["CMwNod::ZZZNoSuchName", "int::ZZZNoSuchName"]
    src, first_line, sentinel_line = build_source(names, "TYPE")
    parse_abort = [_err(first_line + 1, "Expected identifier")]
    check(
        "a parse abort must not turn a companion's silence into ACCEPTED",
        attribute(names, first_line, parse_abort, sentinel_line)["CMwNod::ZZZNoSuchName"],
        None,
    )
    check(
        "the name that actually failed keeps its message",
        attribute(names, first_line, parse_abort, sentinel_line)["int::ZZZNoSuchName"],
        "Expected identifier",
    )

    # Nothing at all came back: the plugin never compiled, the log window was
    # missed, the game died mid-run. Silence proves nothing about any name.
    check(
        "no diagnostics at all is UNKNOWN for every name, never ACCEPTED",
        attribute(names, first_line, [], sentinel_line),
        {"CMwNod::ZZZNoSuchName": None, "int::ZZZNoSuchName": None},
    )

    # Good path: the sentinel fired, so analysis reached the end of the unit and
    # silence on a line is real evidence that the game accepted that name.
    good = [
        _err(sentinel_line, f"Identifier '{SENTINEL_TYPE}' is not a data type"),
        _err(first_line + 1, "Identifier 'ZZZNoSuchName' is not a data type"),
    ]
    check(
        "with the sentinel present, silence means ACCEPTED",
        attribute(names, first_line, good, sentinel_line),
        {
            "CMwNod::ZZZNoSuchName": "",
            "int::ZZZNoSuchName": "Identifier 'ZZZNoSuchName' is not a data type",
        },
    )

    # A semantic reject inside a healthy batch still rejects.
    check(
        "a genuine semantic reject survives batching",
        attribute(names, first_line, good, sentinel_line)["int::ZZZNoSuchName"],
        "Identifier 'ZZZNoSuchName' is not a data type",
    )

    # A single name is the isolation path. Its OWN parse error still reports as
    # a rejection -- the diagnostic names its line, which is evidence, not
    # silence -- even though that same error takes the sentinel down with it.
    solo = ["int::ZZZNoSuchName"]
    s_src, s_first, s_sent = build_source(solo, "TYPE")
    check(
        "an isolated name's own parse error is a REJECT, not an UNKNOWN",
        attribute(solo, s_first, [_err(s_first, "Expected identifier")], s_sent),
        {"int::ZZZNoSuchName": "Expected identifier"},
    )
    check(
        "an isolated name with no diagnostic and no sentinel stays UNKNOWN",
        attribute(solo, s_first, [], s_sent),
        {"int::ZZZNoSuchName": None},
    )

    # Both templates must carry a sentinel, or VALUE runs keep the old defect.
    for template in ("TYPE", "VALUE"):
        t_src, t_first, t_sent = build_source(["Foo"], template)
        lines = t_src.split("\n")
        check(
            f"{template}: sentinel line is inside the generated source",
            1 <= t_sent <= len(lines),
            True,
        )
        check(
            f"{template}: the sentinel line actually mentions the sentinel name",
            SENTINEL_TYPE in lines[t_sent - 1] or SENTINEL_VALUE in lines[t_sent - 1],
            True,
        )
        check(
            f"{template}: the first probed name is at first_line",
            "Foo" in lines[t_first - 1],
            True,
        )

    # ---- codex review of cde4122: four confirmed defects -----------------

    # `read_log_window` keeps every line containing "ERR", from ANY plugin, and
    # attribution matched on line NUMBER alone. Another plugin compiling in the
    # same window therefore lands an error on our sentinel's line number and
    # certifies a unit that never ran -- rebuilding the exact false-ACCEPT path
    # this fix exists to close.
    foreign = [dict(_err(sentinel_line, "some other plugin's problem"), file="other/Main.as")]
    check(
        "a foreign plugin's error must not certify our sentinel",
        attribute(names, first_line, foreign, sentinel_line),
        {"CMwNod::ZZZNoSuchName": None, "int::ZZZNoSuchName": None},
    )
    # And the mirror: through the believe-a-diagnostic asymmetry, a foreign
    # error on a candidate's line would forge a REJECT against an innocent name.
    foreign_hit = [
        _err(sentinel_line, f"Identifier '{SENTINEL_TYPE}' is not a data type"),
        dict(_err(first_line, "some other plugin's problem"), file="other/Main.as"),
    ]
    check(
        "a foreign plugin's error must not forge a REJECT",
        attribute(names, first_line, foreign_hit, sentinel_line)["CMwNod::ZZZNoSuchName"],
        "",
    )

    # An isolated owner probe that comes back unknown must not read as "the
    # game does not accept this name" -- that is the B068 collapse in miniature,
    # one layer up.
    check(
        "an undetermined owner probe is not a negative answer",
        type_accepts(None),
        None,
    )
    check("an accepted owner probe is True", type_accepts(""), True)
    check("a rejected owner probe is False", type_accepts("nope"), False)

    # ---- the retry policy, driven by a simulated compiler ----------------
    #
    # `_FakeGame` reproduces the one behaviour that causes B068: a parse error
    # aborts the unit, so NOTHING else in it is analysed. It runs the real
    # build_source and the real attribute, so these check the actual code path
    # and not a restatement of it.
    game = _FakeGame(parse_errors={"int::ZZZNoSuchName"}, semantic_rejects={"CMwNod::Nope"})

    got = probe(["CMwNod::Nope", "int::ZZZNoSuchName", "CMwNod"], "TYPE", batch=3, runner=game)
    check(
        "after a parse abort, isolation recovers every companion's real verdict",
        got,
        {
            "CMwNod::Nope": "Identifier 'CMwNod::Nope' is not a data type",
            "int::ZZZNoSuchName": "Expected identifier",
            "CMwNod": "",
        },
    )
    check(
        "the batch was actually retried name-by-name",
        game.calls[0:1] + sorted(game.calls[1:]),
        [["CMwNod::Nope", "int::ZZZNoSuchName", "CMwNod"], ["CMwNod"], ["CMwNod::Nope"]],
    )

    # The good path must be untouched: batching without a parse error has to
    # agree with probing the same names one at a time, or the fix has changed
    # answers rather than protecting them.
    clean = _FakeGame(parse_errors=set(), semantic_rejects={"CMwNod::Nope"})
    names3 = ["CMwNod::Nope", "CMwNod", "UI::VirtualKey"]
    batched = probe(names3, "TYPE", batch=3, runner=clean)
    isolated = probe(names3, "TYPE", batch=1, runner=clean)
    check("a healthy batch agrees with isolated probing", batched, isolated)
    check("and it took one round trip, not three", len(clean.calls), 1 + 3)
    check("a genuine accept is still ACCEPTED", batched["CMwNod"], "")

    # A batch size below 1 made `range(0, n, batch)` empty, so probe() returned
    # {} and the writers emitted a header-only corpus with exit 0.
    for bad in (0, -1, -200):
        try:
            probe(["A", "B"], "TYPE", batch=bad, runner=clean)
            failures.append(f"batch={bad} must be rejected, but probe() accepted it")
        except ValueError:
            pass

    # An unusable corpus must never land on the path the Rust suite reads.
    with tempfile.TemporaryDirectory(prefix="b068-selftest-") as tmp:
        dest = Path(tmp) / "corpus.tsv"
        dest.write_text("PREVIOUS GOOD CORPUS\n")
        publish(dest, "rows with unknowns\n", undetermined=3, what="T")
        check(
            "a corpus with unknowns must not overwrite the real one",
            dest.read_text(),
            "PREVIOUS GOOD CORPUS\n",
        )
        partial = Path(tmp) / "corpus.tsv.partial"
        # `exists()` first: reading a missing file raises, and a crash reports
        # which LINE blew up rather than which PROPERTY failed -- and is easy
        # to mistake for a clean run when scanning output for "FAIL".
        check("it is parked beside it instead", partial.exists(), True)
        if partial.exists():
            check("with the rejected content", partial.read_text(), "rows with unknowns\n")
        publish(dest, "clean rows\n", undetermined=0, what="T")
        check("a determinate corpus does get published", dest.read_text(), "clean rows\n")
        # The .partial from the failed run above must not outlive it: left
        # beside a now-good corpus it reads as if this run had failed too.
        check("a successful run clears the stale .partial", partial.exists(), False)

    # The VALUE template has its own line offset and its own sentinel, so the
    # abort-and-isolate path has to be exercised there too, not just for TYPE.
    vgame = _FakeGame(parse_errors={"BadValue"}, semantic_rejects={"GoneValue"})
    check(
        "VALUE: a parse abort is recovered by isolation just like TYPE",
        probe(["GoneValue", "BadValue", "FineValue"], "VALUE", batch=3, runner=vgame),
        {
            "GoneValue": "Identifier 'GoneValue' is not a data type",
            "BadValue": "Expected identifier",
            "FineValue": "",
        },
    )

    # The verdict mapping must carry the third state all the way to the corpus.
    check("b053: UNDETERMINED survives", value_verdict(None), "UNDETERMINED")
    check("b053: accept", value_verdict(""), "ACCEPTED")
    check("b053: no symbol", value_verdict("No matching symbol 'X'"), "NO_SYMBOL")
    check(
        "b053: ambiguous",
        value_verdict("Found multiple matching enum values"),
        "AMBIGUOUS",
    )
    check("b053: other", value_verdict("something else"), "OTHER")
    check("UNDETERMINED reaches the corpus", type_verdict(None), "UNDETERMINED")
    check("an accept is still ACCEPTED", type_verdict(""), "ACCEPTED")
    check("a reject is still REJECTED", type_verdict("Expected identifier"), "REJECTED")

    # `--batch` was accepted, documented as a speed knob, and then ignored by
    # BOTH corpus writers -- the only two callers that matter. A flag that
    # silently does nothing is worse than no flag.
    seen_batches: list[int] = []
    real_probe = globals()["probe"]

    def _recording_probe(names, template, batch=200, runner=None):
        seen_batches.append(batch)
        return real_probe(names, template, batch=batch, runner=clean)

    real_route = fleet.rb_route
    globals()["probe"] = _recording_probe
    fleet.rb_route = lambda *a, **k: {"data": "selftest"}
    try:
        with tempfile.TemporaryDirectory(prefix="b068-batch-") as tmp:
            enums = [{"anonymous": False, "key": "Meta::Foo", "values": [("A", 0)]}]
            write_b052(enums, Path(tmp) / "b052.tsv", batch=7)
            check("write_b052 forwards --batch", seen_batches[0], 7)
            seen_batches.clear()
            write_b053(enums, Path(tmp) / "b053.tsv", batch=9)
            check("write_b053 forwards --batch", seen_batches[0], 9)
    finally:
        globals()["probe"] = real_probe
        fleet.rb_route = real_route

    # The one integration the synthetic fixtures cannot reach: the real log
    # format must actually produce the `file` value the filter demands. This
    # line is copied verbatim from Openplanet.log; Proton renders the Windows
    # path with forward slashes, which is what makes the regex work at all.
    real_line = (
        "[    ScriptEngine] [ERROR] [04:46:07.584] [RemoteBuild]  "
        "C:/users/steamuser/OpenplanetNext/Plugins/lsp-enum-corpus-probe/Main.as "
        "(2, 7) :  ERR : Identifier 'ZZZNoSuchEnumName' is not a data type"
    )
    parsed = fleet.parse_game_diagnostics(real_line)
    check("a real log line parses to exactly one diagnostic", len(parsed), 1)
    if parsed:
        check(
            "and its file is what the attribution filter requires",
            parsed[0]["file"],
            PROBE_FILE,
        )
        check(
            "a real diagnostic survives the filter",
            attribute(["X"], 2, parsed, 3)["X"],
            "Identifier 'ZZZNoSuchEnumName' is not a data type",
        )

    if failures:
        print(f"FAIL: {len(failures)} selftest check(s) failed", file=sys.stderr)
        for f in failures:
            print(f"  - {f}", file=sys.stderr)
        return 1
    print("PASS: attribution never reports ACCEPTED on unproven silence.")
    return 0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dump-enums", type=Path, help="write the loader's enum keys and stop")
    ap.add_argument("--b052", type=Path, help="regenerate the qualified-spelling corpus")
    ap.add_argument("--b053", type=Path, help="regenerate the bare-value corpus")
    ap.add_argument("--names", help="probe an explicit newline-separated list ('-' for stdin)")
    ap.add_argument("--template", default="TYPE", choices=["TYPE", "VALUE"])
    ap.add_argument(
        "--batch",
        type=int,
        default=200,
        help="names per compilation unit, >= 1 (1 = fully isolated; the "
        "sentinel makes any size safe, so this is a speed knob, not a "
        "correctness one)",
    )
    ap.add_argument(
        "--selftest",
        action="store_true",
        help="run the offline attribution checks (no game needed) and stop",
    )
    a = ap.parse_args()

    if a.batch < 1:
        ap.error(f"--batch must be >= 1, got {a.batch}")

    if a.selftest:
        sys.exit(run_selftest())

    if a.names:
        text = sys.stdin.read() if a.names == "-" else Path(a.names).read_text()
        names = [n for n in text.splitlines() if n.strip()]
        for n, msg in probe(names, a.template, batch=a.batch).items():
            tag = "UNKNOWN" if msg is None else ("REJECT" if msg else "ACCEPT")
            print(f"{tag}\t{n}\t{msg or ''}")
        return

    scratch = Path(a.dump_enums or (REPO / "target" / "probe-enums.jsonl"))
    scratch.parent.mkdir(parents=True, exist_ok=True)
    enums = dump_enums(scratch)
    print(f"loader reported {len(enums)} enum keys", file=sys.stderr)
    if a.dump_enums:
        return
    undetermined = 0
    if a.b052:
        undetermined += write_b052(enums, a.b052, batch=a.batch)
    if a.b053:
        undetermined += write_b053(enums, a.b053, batch=a.batch)
    if not (a.b052 or a.b053):
        ap.error("nothing to do: pass --b052, --b053, --names or --dump-enums")

    if undetermined:
        # Exit loudly rather than hand a corpus with unknowns to the suite.
        # The two consumers disagree about how safe that is:
        # `global_scope.rs` panics on a verdict it does not recognise, but
        # `resolver.rs` computes `verdict == "ACCEPTED"`, so an UNDETERMINED
        # row there silently becomes "the LSP must REJECT this spelling" --
        # an unknown asserted as a fact, which is the family of defect this
        # script was just fixed for.
        sys.exit(
            f"error: {undetermined} name(s) could not be determined even in "
            "isolation and were written as UNDETERMINED. Resolve them before "
            "using this corpus: resolver.rs reads an unrecognised verdict as "
            "REJECTED without complaining."
        )


if __name__ == "__main__":
    main()
