#!/usr/bin/env python3
"""
probe_enum_corpus.py — regenerate the game-verdict corpora in docs/probes/.

Submits enum spellings and bare enum-value names to the LIVE game compiler
(Openplanet RemoteBuild) and records what it says, verbatim. Produced the two
tables B056 and B057 cite as their starting corpus.

    scripts/probe_enum_corpus.py --dump-enums out.jsonl
    scripts/probe_enum_corpus.py --b052 docs/probes/b052-qualified-enum-spellings.tsv
    scripts/probe_enum_corpus.py --b053 docs/probes/b053-bare-enum-values.tsv
    echo 'UI::VirtualKey' | scripts/probe_enum_corpus.py --names - --template TYPE
    scripts/probe_enum_corpus.py --selftest      # offline, no game needed

Requires Trackmania + Openplanet running with RemoteBuild on 127.0.0.1:30000.
There is ONE game on ONE port and lanes share it — coordinate before running.
Never writes the fleet ledger.

READ docs/probes/README.md FIRST. In particular: a game REJECT is evidence
about the engine, a game ACCEPT on an unrecognised prefix may only be an
artefact of that machine's installed plugins.

Every batch carries a SENTINEL name the game must reject, on the last probed
line. Absence of a diagnostic counts as ACCEPTED only when that sentinel's
diagnostic came back, proving analysis reached the end of the unit; otherwise
the name is UNDETERMINED and re-probed alone. Without that control a single
parse error aborted the whole compilation unit and every other name in the
batch was recorded ACCEPTED — see B068, and `just probe-selftest`, which
checks this offline.

The candidate list is built from the crate's OWN loader (`--dump-enums`, which
runs the `zz_probe_enum_dump` test), never by re-deriving key generation in
Python. Re-deriving is what produced two confidently wrong counts in this
repo's history — see B046 and B053.
"""
from __future__ import annotations

