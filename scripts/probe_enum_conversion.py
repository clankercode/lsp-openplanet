#!/usr/bin/env python3
"""B071/B148: enum conversion and enum-member verdicts from the LIVE game.

Regenerates the ENGINE columns of `docs/probes/b071-enum-conversion.tsv`, the
second of B129's two orphan corpora.

# THIS CORPUS IS A HYBRID, AND THE GENERATOR OWNS ONLY HALF OF IT

Unlike every other corpus in the manifest, b071 is not purely engine-derived.
Its columns split:

    row, case, fixture     the experiment's own definition
    game_verdict           MEASURED HERE, from the live engine
    game_message           MEASURED HERE, from the live engine
    lsp_today              OUR OWN BINARY's behaviour, measured once at commit
                           a586825 (pre-fix master) and deliberately frozen

`lsp_today` is the evidence the ticket was opened on. Its own preamble says
overwriting it "would erase the evidence the ticket was opened on", and it
cannot be re-derived from the game at ALL — it is a fact about this repo's
history, not about Openplanet. So this generator CARRIES IT FORWARD from the
committed file and refuses to run without one, rather than fabricating a value
or silently dropping the column.

ROW 3 IS PRESERVED, NOT RE-RUN. It records a measurement that turned out to be
INVALID: the fixture used `EDummyCollectionIdent::Undefined`, a value that does
not exist in the live game. The corpus keeps it deliberately — "deleting a
measurement that turned out to be invalid hides the fact that the corpus was
once wrong" — so re-running it would be meaningless and dropping it would
destroy the record. It is copied through untouched.

That makes this the manifest's clearest case that `generator=` is not always
"regenerate the whole file". A regenerator which assumed it owned every column
would have quietly destroyed two things no probe can recover.

# Controls, both polarities (B086), run in the same session as the samples

    r0-control-accept   enum LocalOne{X} LocalOne a = LocalOne::X;  -> CLEAN
    rX-control-reject   ZZZNoSuchType q;                            -> REJECT

An oracle that cannot fail proves nothing about the rows; an oracle never shown
to say CLEAN cannot mean anything by REJECT.

# Names are NOT suffixed, deliberately

Other probes in this repo suffix every declared name so nothing collides with
the ~40 plugins loaded in the shared game. Here the declarations are plain
plugin-local enums in separate AngelScript modules, which do not leak, AND the
engine's message TEXT quotes the enum name — so suffixing would change
`Can't implicitly convert from 'LocalOne' to 'LocalTwo'` into a string that
differs from the committed corpus for a reason that has nothing to do with the
engine. The like-for-like diff is worth more than a redundant guard.
"""

from __future__ import annotations

import argparse
import csv
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import fleet_dogfood as fleet  # noqa: E402
import issue_repro_game as repro  # noqa: E402

TOKEN = "B071EC"
CORPUS = HERE.parent / "docs/probes/b071-enum-conversion.tsv"

CLEAN, REJECT, AMBIGUOUS, INVALID = "CLEAN", "REJECT", "AMBIGUOUS", "INVALID"

SENTINEL = "# --- HAND-WRITTEN NOTES BELOW ARE PRESERVED ACROSS REGENERATIONS (B148) ---"

# Preamble lines the MACHINE owns and rewrites every run. Everything else in
# the committed preamble is human prose and is carried forward verbatim.
MACHINE_LINES = (
    "# B071 probe corpus", "# Trackmania + Openplanet", "# Generated by",
    "# the machine, never typed", "# {date}",
)


def preserved_notes(path: Path) -> list[str]:
    """The hand-written half of the committed preamble, carried forward.

    THE MISTAKE THIS EXISTS TO UNDO. The first version of this generator
    protected the `lsp_today` COLUMN and then overwrote the 80-line PREAMBLE
    with an 18-line machine header — destroying the CONFOUND-FOUND-AND-CLEARED
    section, the anti-vacuity reasoning behind `lsp_today`, the READING THIS
    TABLE guidance, and a 151-plugin false-positive sweep. None of that is
    derivable from the game, and losing it is the precise failure B129 argued
    about when it decided hand-measured content stays manual.

    So prose is treated exactly like `lsp_today`: the generator owns the stamp
    lines and nothing else. A file already carrying the sentinel keeps
    everything below it; a file predating the sentinel keeps every comment
    line that is not machine-owned.
    """
    if not path.exists():
        return []
    lines = [l for l in path.read_text(encoding="utf8").splitlines() if l.startswith("#")]
    if SENTINEL in lines:
        return lines[lines.index(SENTINEL) + 1:]
    return [l for l in lines if not any(l.startswith(m) for m in MACHINE_LINES)]

# Rows preserved verbatim rather than re-measured (see the module docstring).
PRESERVED_ROWS = {"3"}


@dataclass
class V:
    id: str
    row: str            # the corpus `row` cell; "" for a control
    case: str
    code: str           # the fixture body, exactly as the corpus records it
    expect: str = "UNKNOWN"
    stands_for: str = ""
    fid: str = ""


def variants() -> list[V]:
    return [
        V(id="r0-control-accept", row="", case="control: oracle accepts",
          code="enum LocalOne{X}\nLocalOne a = LocalOne::X;\n",
          expect=CLEAN,
          stands_for="the ACCEPT pole: a valid enum member read, which every "
                     "shipped plugin using enums performs"),
        V(id="rX-control-reject", row="", case="control: oracle rejects",
          code="ZZZNoSuchType q;\n",
          expect=REJECT,
          stands_for="the REJECT pole: an unknown type, so the oracle is shown "
                     "to be able to fail"),
        V(id="r1", row="1", case="enum A -> enum B (engine)",
          code="EDummyCollectionIdent a;\nEGhostNameLogoType b = a;\n",
          stands_for="a plugin assigning one engine enum to another; the "
                     "checker's cross-enum conversion rule"),
        V(id="r2", row="2", case="enum A -> enum B (workspace)",
          code="enum LocalOne{X}\nenum LocalTwo{Y}\nLocalOne c = LocalOne::X;\n"
               "LocalTwo d = c;\n",
          stands_for="the same rule for enums the workspace declares itself"),
        V(id="r4", row="4", case="enum -> int (workspace)",
          code="enum LocalOne{X}\nLocalOne a = LocalOne::X;\nint b = a;\n",
          stands_for="enum-to-int widening, which the LSP must stay SILENT "
                     "about; a diagnostic here would be a false positive"),
        V(id="r5", row="5", case="enum -> int (engine, verified value)",
          code="VirtualKey a = VirtualKey::A;\nint b = a;\n",
          stands_for="the same widening for an engine enum, using a value "
                     "already recorded as a live ACCEPT in b053"),
        V(id="r6", row="6", case="int -> enum (engine, verified)",
          code="int a = 0;\nVirtualKey b = a;\n",
          stands_for="the NARROWING direction, which the engine rejects"),
        V(id="r7", row="7", case="bad member, engine enum",
          code="auto b = VirtualKey::ZZZNotAValue;\n",
          stands_for="a misspelled member of an engine enum"),
        V(id="r8", row="8", case="bad member, workspace enum",
          code="enum LocalOne{X}\nLocalOne a = LocalOne::ZZZNotAValue;\n",
          stands_for="a misspelled member of a workspace enum"),
    ]


def classify(rec: dict) -> tuple[str, str]:
    """`(verdict, engine message)` for one fixture. Never guesses."""
    status = rec.get("build_status", "NOT-RUN")
    if status == "NOT-RUN":
        return AMBIGUOUS, "the build never started; nothing was measured"
    if rec.get("contended"):
        return AMBIGUOUS, "another session's errors shared the log window"
    msg = ""
    for d in rec.get("game_errors", []) or []:
        t = (d.get("msg") or "").strip()
        if t:
            msg = t
            break
    if status == "CLEAN":
        return CLEAN, ""
    if status == "REJECTED":
        if not msg:
            return AMBIGUOUS, "REJECTED with no attributed message; cannot say why"
        return REJECT, msg
    return AMBIGUOUS, f"build_status={status}"


def load_committed() -> dict[str, dict]:
    """The committed corpus, keyed by `row`.

    Required, not optional: `lsp_today` and row 3 cannot be re-derived from the
    game, so a run without this file could only fabricate them.
    """
    if not CORPUS.exists():
        raise SystemExit(
            f"{CORPUS} is missing. This generator owns only the engine columns; "
            "`lsp_today` is this repo's own history at commit a586825 and row 3 is "
            "a deliberately retained INVALID measurement. Neither can be "
            "regenerated, so refusing to write a corpus that would drop them."
        )
    lines = [l for l in CORPUS.read_text(encoding="utf8").splitlines()
             if l.strip() and not l.startswith("#")]
    out = {}
    for r in csv.DictReader(lines, delimiter="\t"):
        out[r["row"]] = r
    return out


def write_fixture(root: Path, v: V) -> Path:
    pretty = f"B071ec {v.id}"
    v.fid = repro.PROBE_PREFIX + fleet.folder_id(pretty)
    plugin = root / re.sub(r"[^A-Za-z0-9-]", "_", v.id)
    plugin.mkdir(parents=True)
    plugin.joinpath("info.toml").write_text(
        "[meta]\n"
        f'name     = "{pretty}"\n'
        'author   = "clankercode"\n'
        'category = "Tests"\n'
        'version  = "0.1.0"\n'
        "\n[script]\n"
    )
    plugin.joinpath("Main.as").write_text(
        f"// B071 enum-conversion probe :: {v.id}\n"
        f"// case: {v.case}\n"
        f"// stands in for: {v.stands_for}\n"
        + v.code
        + "\nvoid Main() {\n"
        f'    print("{TOKEN} {v.id} ready");\n'
        "}\n"
    )
    return plugin


def run_selftest() -> int:
    failures: list[str] = []

    def check(name: str, cond: bool, why: str = "") -> None:
        if not cond:
            failures.append(f"{name}: {why}")

    vs = variants()
    for p in fleet.probe_variant_problems(vs):
        failures.append(f"variant table: {p}")
    for v in vs:
        check(f"stands_for {v.id}", bool(v.stands_for), "empty")
        check(f"code {v.id}", bool(v.code.strip()), "empty fixture")
        check(f"probe id valid {v.id}", repro._valid_probe_id(
            repro.PROBE_PREFIX + fleet.folder_id(f"B071ec {v.id}")), "invalid fid")

    ids = [v.id for v in vs]
    check("ids unique", len(ids) == len(set(ids)), "duplicate id")

    # The committed corpus must be readable, and must still carry the two
    # things this generator cannot produce.
    committed = load_committed()
    check("row 3 is preserved in the committed corpus", "3" in committed,
          "the retained INVALID row is gone")
    check("row 3 is still INVALID", committed.get("3", {}).get("game_verdict") == INVALID,
          "row 3 changed verdict; it records a measurement known to be invalid")
    # VALUE, not just key presence: a blanked column still has the key, and
    # `lsp_today` is unrecoverable — it is this repo's behaviour at a commit,
    # not anything the game can be asked about.
    check("lsp_today column survives",
          all(r.get("lsp_today", "").strip() for r in committed.values()),
          "the frozen lsp_today column is missing or blank")
    check("every runnable row has a variant",
          {v.row for v in vs if v.row} | PRESERVED_ROWS == set(committed),
          f"variants cover {sorted({v.row for v in vs if v.row})}, corpus has "
          f"{sorted(committed)}")

    # Verdict logic: failure to measure is never a verdict (B118).
    check("NOT-RUN is AMBIGUOUS", classify({"build_status": "NOT-RUN"})[0] == AMBIGUOUS)
    check("contended is AMBIGUOUS",
          classify({"build_status": "REJECTED", "contended": True,
                    "game_errors": [{"msg": "x"}]})[0] == AMBIGUOUS)
    check("BUILD-ERR is AMBIGUOUS", classify({"build_status": "BUILD-ERR"})[0] == AMBIGUOUS)
    check("clean is CLEAN", classify({"build_status": "CLEAN"})[0] == CLEAN)
    check("rejected with a message is REJECT",
          classify({"build_status": "REJECTED",
                    "game_errors": [{"msg": "Can't implicitly convert"}]}) ==
          (REJECT, "Can't implicitly convert"))
    # A REJECTED build whose message we cannot attribute is not a REJECT datum:
    # the corpus's value is the message, so a rejection with no message has not
    # answered the question the row asks.
    check("rejected with no message is AMBIGUOUS",
          classify({"build_status": "REJECTED", "game_errors": []})[0] == AMBIGUOUS,
          "a rejection with no attributed text was recorded as a measurement")
    check("foreign errors are not ours",
          classify({"build_status": "REJECTED", "game_errors": [],
                    "foreign_errors": [{"msg": "theirs"}]})[0] == AMBIGUOUS)

    # PROSE IS PRESERVED, and the check is on CONTENT, not merely on a line
    # count: the generator once rewrote 80 hand-written lines as 18 machine
    # ones while every column check still passed.
    notes = preserved_notes(CORPUS)
    check("hand-written notes survive", len(notes) >= 40,
          f"only {len(notes)} preamble lines carried forward; the committed prose "
          f"is not derivable from any game and cannot be regenerated")
    joined = "\n".join(notes)
    for landmark in ("CONFOUND", "lsp_today", "READING THIS TABLE",
                     "FALSE-POSITIVE SWEEP", "WORDING"):
        check(f"preamble keeps {landmark!r}", landmark in joined,
              "a named section of the hand-written methodology was dropped")

    print(f"b071 probe selftest: {len(vs)} variants, {len(failures)} failure(s)")
    for f in failures:
        print(f"  FAIL {f}")
    return 1 if failures else 0


def _live_version() -> tuple[str, str]:
    try:
        import regen_golds  # noqa: PLC0415
        return (regen_golds.live_engine_version() or "UNKNOWN",
                regen_golds.live_engine_build() or "UNKNOWN")
    except Exception:
        return ("UNKNOWN", "UNKNOWN")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv")
    ap.add_argument("--only")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return run_selftest()

    committed = load_committed()
    vs = variants()
    if args.only:
        vs = [v for v in vs if v.id.startswith(args.only)]
        if not vs:
            print(f"no variant matches {args.only!r}", file=sys.stderr)
            return 2

    problems = fleet.probe_variant_problems(vs)
    if problems:
        print("THE VARIANT TABLE CANNOT MEASURE:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 5
    if not fleet.game_alive():
        print("game/RemoteBuild not reachable; refusing to report a verdict", file=sys.stderr)
        return 3
    strays = repro.probe_dirs_present(fleet.OPN_PLUGINS)
    if strays:
        print(f"stranded probe fixtures present, refusing to run (B077): {strays}",
              file=sys.stderr)
        return 4

    version = _live_version()
    tmp = Path(tempfile.mkdtemp(prefix="b071ec-"))
    rows: list[dict] = []
    try:
        for v in vs:
            rec = repro.probe(write_fixture(tmp, v))
            verdict, msg = classify(rec)
            rows.append({
                "id": v.id, "row": v.row, "case": v.case,
                "verdict": verdict, "message": msg,
                "expect": v.expect, "stands_for": v.stands_for, "reason": msg,
            })
            flag = ""
            if v.expect != "UNKNOWN":
                flag = "  <-- CONTROL OK" if verdict == v.expect else \
                       f"  <-- CONTROL FAILED (expected {v.expect})"
            print(f"{verdict:10s} {v.id:20s} {msg[:70]}{flag}", flush=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    left = repro.probe_dirs_present(fleet.OPN_PLUGINS)
    print()
    print(f"B077 sweep: {'clean' if not left else 'STRANDED: ' + repr(left)}")
    run_problems = fleet.probe_run_problems(rows)
    if run_problems:
        print("THE RUN IS NOT EVIDENCE:", file=sys.stderr)
        for pr in run_problems:
            print(f"  - {pr}", file=sys.stderr)

    if args.tsv:
        _write_tsv(Path(args.tsv), rows, committed, version)
        print(f"\nwrote {args.tsv}")

    if run_problems or left:
        return 1
    bad = [r for r in rows if r["expect"] != "UNKNOWN" and r["verdict"] != r["expect"]]
    return 1 if bad else 0


def _write_tsv(path: Path, rows: list[dict], committed: dict[str, dict],
               version: tuple[str, str]) -> None:
    import datetime
    ver, build = version
    # Read BEFORE the file is opened for writing, or the prose is already gone.
    notes = preserved_notes(CORPUS)
    measured = {r["row"]: r for r in rows if r["row"]}
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as fh:
        fh.write("# B071 probe corpus - enum conversion and enum-member verdicts, LIVE game.\n")
        fh.write(f"# Trackmania + Openplanet {ver} ({build}), RemoteBuild 127.0.0.1:30000,\n")
        fh.write(f"# {datetime.date.today().isoformat()}. Stamp read from Openplanet.log by\n")
        fh.write("# the machine, never typed by a human (B148).\n")
        fh.write("# Generated by scripts/probe_enum_conversion.py.\n")
        fh.write("#\n")
        fh.write("# THE GENERATOR OWNS ONLY game_verdict AND game_message. `lsp_today` is\n")
        fh.write("# THIS REPO's behaviour at commit a586825 (pre-fix master) and is carried\n")
        fh.write("# forward verbatim -- it is a fact about our history, not about Openplanet,\n")
        fh.write("# and it is the evidence B071 was opened on.\n")
        fh.write("#\n")
        fh.write("# ROW 3 IS PRESERVED, NOT RE-RUN. It records a measurement that turned out\n")
        fh.write("# to be INVALID (the fixture used a non-existent enum value). Deleting it\n")
        fh.write("# would hide that the corpus was once wrong, which is the most transferable\n")
        fh.write("# thing in this file.\n")
        fh.write("#\n")
        fh.write("# METHOD. One fixture, one plugin, one compilation unit (B068). Controls of\n")
        fh.write("# both polarities ran in the same session.\n")
        fh.write("#\n")
        fh.write(SENTINEL + "\n")
        for line in notes:
            fh.write(line.rstrip() + "\n")
        fh.write("row\tcase\tfixture\tgame_verdict\tgame_message\tlsp_today\n")
        for key in sorted(committed, key=lambda k: int(k)):
            old = committed[key]
            if key in PRESERVED_ROWS or key not in measured:
                fh.write("\t".join([old["row"], old["case"], old["fixture"],
                                    old["game_verdict"], old["game_message"],
                                    old["lsp_today"]]) + "\n")
                continue
            new = measured[key]
            fh.write("\t".join([old["row"], old["case"], old["fixture"],
                                new["verdict"], new["message"],
                                old["lsp_today"]]) + "\n")


if __name__ == "__main__":
    sys.exit(main())
